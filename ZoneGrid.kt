    fun nearest(lat: Double, lon: Double): SurgeZone =
        zones.minByOrNull { distanceKm(lat, lon, it.lat, it.lon) } ?: zones.first()

    /** Поиск по названию из строки поиска: точное слово, затем вхождение. */
    fun search(q: String): SurgeZone? {
        val s = q.trim().lowercase()
        if (s.length < 3) return null
        zones.firstOrNull { z ->
            z.name.lowercase().removePrefix("мо: ").split("/", ":", "(", ")")
                .map { it.trim() }.any { it == s }
        }?.let { return it }
        return zones.firstOrNull { it.name.lowercase().contains(s) }
    }

    fun byText(text: String): SurgeZone? {
        val lower = text.lowercase()
        return zones.firstOrNull { zone ->
            zone.name.split("/", "(", ")", ":", " ").any { token ->
                token.length >= 5 && lower.contains(token.lowercase())
            }
        }
    }

    fun distanceKm(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val r = 6371.0
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val a = sin(dLat / 2).pow(2) +
                cos(Math.toRadians(lat1)) * cos(Math.toRadians(lat2)) * sin(dLon / 2).pow(2)
        return r * 2 * atan2(sqrt(a), sqrt(1 - a))
    }
